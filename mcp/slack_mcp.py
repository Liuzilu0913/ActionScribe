"""
mcp/slack_mcp.py
─────────────────
Slack Incoming Webhook integration — posts meeting action summaries.

Requires:
  SLACK_WEBHOOK_URL — Webhook URL from api.slack.com/apps

No GPU required — pure REST API call via requests.
"""

import logging
import os
from typing import Any, Dict, List

import requests

logger = logging.getLogger(__name__)

# Emoji mapping by priority label
PRIORITY_EMOJI: Dict[str, str] = {
    "Critical": "🔴",
    "High": "🟡",
    "Medium": "🟢",
    "Low": "⚪",
}


def build_slack_message(tasks: List[Dict[str, Any]]) -> str:
    """
    Build a readable Slack message from the list of action items.

    Tasks are sorted by priority_score (highest first).

    Args:
        tasks: List of validated ActionItem dicts.

    Returns:
        Formatted Slack message string.
    """
    if not tasks:
        return "🤖 *AI Meeting Pipeline* — No action items were extracted from this meeting."

    # Sort highest priority first
    sorted_tasks = sorted(
        tasks, key=lambda x: x.get("priority_score", 0), reverse=True
    )

    total = len(sorted_tasks)
    lines = [f"🤖 *AI Meeting Action Summary — {total} Item{'s' if total != 1 else ''}*\n"]

    for i, task in enumerate(sorted_tasks, 1):
        label = task.get("priority_label", "Medium")
        emoji = PRIORITY_EMOJI.get(label, "⚫")
        owner = task.get("owner", "TBD")
        deadline = task.get("deadline", "TBD")
        action = task.get("task", "Unknown task")
        score = task.get("priority_score", "?")
        needs_review = task.get("needs_review", False)

        review_flag = " ⚠️ _needs review_" if needs_review else ""

        lines.append(
            f"{i}. {emoji} *[{label} | Score: {score}]* {action}{review_flag}\n"
            f"   👤 Owner: `{owner}`  📅 Deadline: `{deadline}`\n"
        )

    lines.append("\n_Generated by AI Meeting-to-Action Pipeline_")
    return "\n".join(lines)


def dispatch_to_slack(tasks: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Post the meeting action summary to a Slack channel via webhook.

    Args:
        tasks: List of validated ActionItem dicts from the formatter.

    Returns:
        {"success": True, "items_sent": N}
        or
        {"success": False, "error": "..."}
    """
    webhook_url = os.getenv("SLACK_WEBHOOK_URL", "")

    if not webhook_url:
        logger.warning("SLACK_WEBHOOK_URL missing — skipping Slack notification.")
        return {
            "success": False,
            "error": "SLACK_WEBHOOK_URL missing. Set it in your .env file.",
        }

    message = build_slack_message(tasks)
    payload = {"text": message}

    try:
        response = requests.post(webhook_url, json=payload, timeout=15)
        response.raise_for_status()
        logger.info("Slack: message sent successfully (%d items).", len(tasks))
        return {
            "success": True,
            "channel": "configured_channel",
            "items_sent": len(tasks),
        }
    except requests.exceptions.HTTPError as e:
        logger.error("Slack webhook HTTP error: %s", str(e))
        return {"success": False, "error": f"Slack HTTP error: {str(e)}"}
    except requests.exceptions.RequestException as e:
        logger.error("Slack webhook request failed: %s", str(e))
        return {"success": False, "error": str(e)}
